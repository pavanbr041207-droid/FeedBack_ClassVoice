-- V1: foundation. Portable SQL (PostgreSQL production, H2 in PostgreSQL mode for dev/tests).

create table roles (
    id   bigint generated by default as identity primary key,
    name varchar(32) not null,
    constraint uk_roles_name unique (name)
);

insert into roles (name) values ('COLLEGE_ADMIN');
insert into roles (name) values ('TEACHER');
insert into roles (name) values ('STUDENT');

create table users (
    id            bigint generated by default as identity primary key,
    username      varchar(64)  not null,
    password_hash varchar(100) not null,
    role_id       bigint       not null,
    status        varchar(24)  not null,
    display_name  varchar(120),
    created_at    timestamp with time zone not null,
    last_login_at timestamp with time zone,
    constraint uk_users_username unique (username),
    constraint fk_users_role foreign key (role_id) references roles (id)
);

create index idx_users_role on users (role_id);

create table college_settings (
    id            bigint generated by default as identity primary key,
    setting_key   varchar(100)  not null,
    setting_value varchar(1000),
    updated_at    timestamp with time zone not null,
    constraint uk_college_settings_key unique (setting_key)
);

insert into college_settings (setting_key, setting_value, updated_at)
values ('college.display_name', 'Your College', current_timestamp);

create table audit_logs (
    id            bigint generated by default as identity primary key,
    actor_user_id bigint,
    action        varchar(64)  not null,
    entity_type   varchar(64),
    entity_id     varchar(64),
    detail        varchar(500),
    created_at    timestamp with time zone not null,
    constraint fk_audit_actor foreign key (actor_user_id) references users (id)
);

create index idx_audit_created on audit_logs (created_at);
create index idx_audit_actor on audit_logs (actor_user_id);

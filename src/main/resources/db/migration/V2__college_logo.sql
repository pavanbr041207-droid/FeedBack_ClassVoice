-- V2: college logo, stored in the database so hosts with ephemeral disks do not lose it.
-- bytea: PostgreSQL native; alias of binary varying in H2 (max 1 MiB by default, app caps at 512 KiB).
create table college_logo (
    id           bigint generated by default as identity primary key,
    content_type varchar(32) not null,
    size_bytes   integer     not null,
    data         bytea       not null,
    updated_at   timestamp with time zone not null
);
